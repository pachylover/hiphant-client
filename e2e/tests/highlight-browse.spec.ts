import { test, expect } from '@playwright/test'

test('홈 배치, 등록 스트리머 검색과 필터 이동', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /HiPhant[\s\S]*치지직 하이라이트 분석기/ })).toBeVisible()
  const recent = page.locator('section').filter({ has: page.getByRole('heading', { name: '최근 생성된 하이라이트' }) })
  await expect(recent.locator('a[href^="/highlights/"]')).toHaveCount(6)
  await expect(page.getByRole('heading', { name: '최근 분석된 방송' })).toHaveCount(0)
  await expect(page.getByText('치지직 다시보기 채팅 내역을 분석하여 채팅이 많았던 구간을 찾습니다.', { exact: false })).toBeVisible()
  await expect(page.getByRole('button', { name: '하이라이트 찾기', exact: true })).toBeVisible()
  const search = page.getByRole('region', { name: '스트리머 찾기', exact: true })
  const searchBox = await search.boundingBox()
  const recentBox = await recent.boundingBox()
  const formBox = await page.getByRole('button', { name: '하이라이트 찾기', exact: true }).boundingBox()
  expect(searchBox!.y).toBeGreaterThan(formBox!.y + formBox!.height)
  expect(searchBox!.y + searchBox!.height).toBeLessThan(recentBox!.y)
  await page.getByRole('textbox', { name: '스트리머 닉네임 검색' }).fill('별빛')
  const streamer = page.getByRole('link', { name: '별빛스트리머', exact: true })
  await expect(streamer).toBeVisible()
  await expect(page.getByRole('link', { name: '달빛스트리머', exact: true })).toHaveCount(0)
  await streamer.click()
  await expect(page).toHaveURL(/channelId=alpha/)
  await expect(page.locator('main a[href^="/highlights/"]')).toHaveCount(8)
})

